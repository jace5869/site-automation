VMCA_RENEW = {
    "vcenter": "the vSphere Client > Administration > Certificate Management > Machine SSL Certificate > Renew",
    "esxi": "the vSphere Client > the host > Configure > System > Certificate > Renew",
}
KEY_NOTE = {
    "vcenter": "made by vCenter and kept in its certificate store (VECS) - it never leaves vCenter and waits there for the issued certificate",
    "esxi": "made by the host and kept on it - it never leaves the host and waits there for the issued certificate",
}


def _pairs(dn):
    """'CN=a, OU=b' -> [('CN', 'a'), ('OU', 'b')] (keys in upper case; an escaped comma kept)."""
    out = []
    for part in re.split(r"(?<!\\)[,+]", str(dn or "")):
        if "=" in part:
            k, v = part.split("=", 1)
            out.append((k.strip().upper(), v.strip().replace("\\,", ",")))
    return out


def vmware_cert_vmca(issuer, patterns=None):
    """Is a certificate signed by vCenter's own CA (VMCA)? Its issuer is VMCA's root - by default
    'CN=CA, DC=vsphere, DC=local, ..., OU=VMware Engineering' - or matches one of patterns (any case,
    * and ? wildcards, e.g. '*O=vc01.yoursite.mil*')."""
    p = _pairs(issuer)
    if ("OU", "VMware Engineering") in p or (("CN", "CA") in p and any(k == "DC" for k, _ in p)):
        return True
    return _named(issuer, patterns)


def _named(issuer, patterns):
    low = str(issuer or "").lower()
    return any(fnmatch.fnmatchcase(low, str(x).lower()) for x in patterns or [] if str(x).strip())


def _only(name, patterns):
    """Named in patterns (any case, wildcards; the short name of a host name matches too)? None = no limit."""
    pats = [str(x).strip().lower() for x in patterns or [] if str(x).strip()]
    if not pats:
        return True
    n = str(name or "").lower()
    short = n if re.match(r"^[0-9.]+$|:", n) else n.split(".")[0]
    return any(fnmatch.fnmatchcase(n, x) or fnmatch.fnmatchcase(short, x) for x in pats)


def _cn(subject, name):
    for k, v in _pairs(subject):
        if k == "CN" and v:
            return "CN=" + v
    return subject or name


def vmware_cert_plan(certs, opts=None):
    """certs (site_vmware_certs read) -> {certs, due, health, left_out}.
    certs: the ones in vmware_cert_only, each with where, signer (VMCA, self-signed, CA), due, severity,
    id (vmware-cert:<kind>:<name>:<expiry> - a renewed certificate is a new problem, a new ticket),
    renew: csr (a CSR is made), vmca (renewed in vCenter) or '' (not due). health: the findings, one
    entry per vCenter and host read - also those with none (so the ServiceNow step notes tickets whose
    certificate was renewed) - as the ServiceNow tickets step reads them. opts: warn_days, crit_days,
    only, vmca_issuers, vmca_csr, job, time."""
    o = opts or {}
    warn, crit = int(o.get("warn_days", 30)), int(o.get("crit_days", 7))
    out, due, health, left = [], [], {}, []
    for c in sorted(certs or [], key=lambda x: (x.get("days", 0), x.get("name", ""))):
        if not _only(c.get("name"), o.get("only")):
            left.append(c.get("name", ""))
            continue
        c = dict(c)
        kind = c.get("kind", "")
        # VMCA's own root signs, never a self-signed certificate - unless the site names that issuer (vmware_cert_vmca_issuers)
        c["vmca"] = (vmware_cert_vmca(c.get("issuer")) and not c.get("self_signed")) or _named(c.get("issuer"), o.get("vmca_issuers"))
        c["signer"] = "VMCA (vCenter's own CA)" if c["vmca"] else ("self-signed" if c.get("self_signed") else "CA")
        c["host"] = c.get("name", "")
        port = int(c.get("port") or 443)
        url = "%s%s" % (c["name"], "" if port == 443 else ":%d" % port)
        c["where"] = ("vCenter %s (Machine SSL certificate, https://%s)" % (c["name"], url)
                      if kind == "vcenter" else "ESXi host %s (vCenter %s)" % (c["name"], c.get("vcenter", "")))
        d = int(c.get("days", 0))
        c["due"] = d <= warn
        c["id"] = "vmware-cert:%s:%s:%s" % (kind, str(c["name"]).lower(), c.get("expires", ""))
        c["renew"] = ("vmca" if c["vmca"] and not o.get("vmca_csr") else "csr") if c["due"] else ""
        h = health.setdefault(c["name"], {"status": "healthy", "checks": [CHECK], "checks_failed": [], "findings": [],
                                          "act": {}, "time": o.get("time", ""), "job": str(o.get("job", "")), "reach": False})
        out.append(c)
        if not c["due"]:
            continue
        c["severity"] = "critical" if d <= crit else "warning"
        when = ("EXPIRED %d days ago" % abs(d) if d < 0 else "expires in %d days" % d) + " (%s)" % c.get("expires", "")
        what = "vCenter Machine SSL certificate" if kind == "vcenter" else "ESXi host certificate"
        notes = ["Due: it expires within vmware_cert_warn_days (%d days)." % warn]
        if c["renew"] == "vmca":
            notes.append("Signed by vCenter's own CA (VMCA): renew it in %s - no CSR is made for it (vmware_cert_vmca_csr: true "
                         "makes one, to replace it with a certificate of your PKI)." % VMCA_RENEW.get(kind, "vCenter"))
        hint = ("echo | openssl s_client -connect %s:%d -servername %s 2>/dev/null | openssl x509 -noout -subject -issuer -dates"
                % (c["name"], port, c["name"])
                if kind == "vcenter" else "the vSphere Client > the host %s > Configure > System > Certificate" % c["name"])
        c["finding"] = {"check": CHECK, "id": c["id"], "severity": c["severity"],
                        "summary": "%s %s %s" % (what, _cn(c.get("subject"), c["name"]), when), "hint": hint, "note": " ".join(notes)}
        h["findings"].append(c["finding"])
        h["status"] = "findings"
        due.append(c)
    return {"certs": out, "due": due, "health": health, "left_out": left}


def vmware_cert_csr_result(due, made, opts=None):
    """The due certificates as the certificate renewal's ServiceNow step reads them (roles/servicenow/tasks/
    cert_csr.yml, _csr_results_in: one result, check vmware_certs): status made (with the CSR), exists (its
    ticket has one), would make (dry run), failed, or skipped with why. made: site_vmware_certs csr's
    'made'; opts: on_ticket {cert id: 'INC... (attached: name)'}, make_csr, connected, without_servicenow,
    check_mode, ext, content_type, retry_txt, report_only (the report job: no CSR, says so)."""
    o = opts or {}
    by = dict(("%s|%s|%s" % (m.get("vcenter"), m.get("kind"), m.get("name")), m) for m in made or [])
    on = o.get("on_ticket") or {}
    out = []
    for c in due or []:
        kind = c.get("kind", "")
        base = "%s%s" % (c.get("name", ""), "-machine-ssl" if kind == "vcenter" else "")
        r = {"host": c.get("name", ""), "subject": c.get("subject", ""), "issuer": c.get("issuer", ""), "expires": c.get("not_after", ""),
             "days": c.get("days", 0), "wheres": [c.get("where", "")], "ids": [c.get("id", "")], "severity": c.get("severity", "warning"),
             "sans": c.get("sans") or [], "self_signed": bool(c.get("self_signed")), "key_note": KEY_NOTE.get(kind, ""),
             "install": VCENTER_INSTALL if kind == "vcenter" else ESXI_INSTALL, "file_name": "%s.%s" % (base, o.get("ext", "csr")),
             "status": "skipped", "reason": ""}
        m = by.get("%s|%s|%s" % (c.get("vcenter"), kind, c.get("name")))
        if o.get("report_only"):
            r["reason"] = "the report only - VMware - certificate renewal opens its incident" + (
                " (renew it in vCenter: VMCA)" if c.get("renew") == "vmca" else " and makes its CSR")
        elif c.get("renew") == "vmca":
            r["reason"] = "signed by vCenter's own CA (VMCA): renew it in %s" % VMCA_RENEW.get(kind, "vCenter")
        elif c.get("id") in on:
            m2 = re.search(r"attached: (.+)\)$", str(on[c["id"]]))
            r.update(status="exists", already="its CSR is on %s already" % on[c["id"]], file_name=m2.group(1) if m2 else r["file_name"])
        elif not o.get("make_csr", True):
            r["reason"] = "vmware_cert_make_csr: false - the incident only"
        elif not o.get("connected") and not o.get("without_servicenow"):
            r["reason"] = ("no ServiceNow API credential: the CSR is made only with its ticket, which keeps it - a second CSR replaces "
                           "the key of the first (vmware_cert_csr_without_servicenow: true makes it and prints it)")
        elif m is None or o.get("check_mode"):
            r["status"] = "would make"
        elif m.get("error"):
            r.update(status="failed", reason=m["error"])
        else:
            r.update(status="made", csr=m["csr"], csr_subject=m.get("csr_subject", ""), sans=m.get("csr_names") or [],
                     sans_same=kind == "vcenter",
                     file_name="%s-%s.%s" % (base, hashlib.sha256(m["csr"].encode("utf-8")).hexdigest()[:8], o.get("ext", "csr")))
        out.append(r)
    return {"host": "vmware", "check": CHECK, "content_type": o.get("content_type", "text/plain"),
            "retry_txt": bool(o.get("retry_txt", True)), "certs": out}


def vmware_cert_report(plan, result, not_checked, table, opts=None):
    """The job's report: what was done with each due certificate, every certificate (table: the
    certificate report's coloured table), the hosts not checked. opts: warn_days, check_mode, tickets
    {cert id: number}, report_only (the report job: what the renewal would do, no ticket column)."""
    o = opts or {}
    dry = bool(o.get("check_mode"))
    ro = bool(o.get("report_only"))
    due = plan.get("due") or []
    res = dict((x["ids"][0], x) for x in (result or {}).get("certs") or [])
    tickets = o.get("tickets") or {}
    nc = not_checked or []
    expired = len([c for c in due if int(c.get("days", 0)) < 0])
    title = "VMware certificate%s%s: %d due within %d days%s, of %d" % (
        " report" if ro else "s", " (dry run)" if dry and not ro else "", len(due), int(o.get("warn_days", 30)),
        (" (%d expired)" % expired) if expired else "", len(plan.get("certs") or []))
    if nc:
        title += ", %d not checked" % len(nc)
    status = "critical" if expired or any(r.get("status") == "failed" for r in res.values()) else ("warning" if due or nc else "ok")
    label = {"made": "CSR made", "exists": "CSR on the ticket already", "would make": "would make a CSR (dry run)",
             "failed": "CSR FAILED", "skipped": "no CSR"}
    rows, rs = [], []
    for c in due:
        r = res.get(c["id"], {})
        what = label.get(r.get("status"), "") + ((": " + r["reason"]) if r.get("reason") else "")
        rows.append([c.get("days"), c.get("expires"), c.get("name"), c.get("signer"), tickets.get(c["id"], "-"), what])
        rs.append("critical" if int(c.get("days", 0)) < 0 or r.get("status") == "failed" else "warning")
    sections = []
    if rows and ro:
        def would(c):
            if c.get("renew") == "vmca":
                return "open an incident: renew it in vCenter (VMCA), no CSR"
            return "open an incident, and make a CSR on %s" % ("vCenter" if c.get("kind") == "vcenter" else "the host")
        sections.append({"title": "Due within %d days - what the renewal would do" % int(o.get("warn_days", 30)),
                         "status": "critical" if "critical" in rs else "warning",
                         "columns": ["Days left", "Expires", "Name", "Signed by", "VMware - certificate renewal would"],
                         "rows": [r[:4] + [would(c)] for r, c in zip(rows, due)], "row_status": rs,
                         "text": "The report only: nothing was sent to ServiceNow and no CSR was made. The job template VMware - "
                                 "certificate renewal opens the incidents and makes the CSRs."})
    elif rows:
        sections.append({"title": "Due - the incident and the CSR of each", "status": "critical" if "critical" in rs else "warning",
                         "columns": ["Days left", "Expires", "Name", "Signed by", "Ticket", "Renewal"], "rows": rows, "row_status": rs,
                         "text": "A CSR is made where the key stays (vCenter, or the host) and attached to the certificate's incident, "
                                 "with what to do next. Signed by VMCA: renewed in vCenter, no CSR."})
    if table:
        sections.append(table)
    if nc:
        sections.append({"title": "Not checked", "status": "warning", "columns": ["Name", "vCenter", "Why"],
                         "rows": [[x.get("name"), x.get("vcenter"), x.get("why")] for x in nc]})
    if plan.get("left_out"):
        sections.append({"title": "Left out (vmware_cert_only)", "lines": [", ".join(plan["left_out"])]})
    return {"title": title, "status": status,
            "subtitle": "Due = expires within vmware_cert_warn_days (%d)%s" % (int(o.get("warn_days", 30)),
                                                                               " - the report only: no incident, no CSR" if ro else
                                                                               " - DRY RUN: no CSR made, nothing sent to ServiceNow" if dry else ""),
            "summary": [{"label": "Certificates", "value": len(plan.get("certs") or [])},
                        {"label": "Due", "value": len(due), "status": "warning" if due else "ok"},
                        {"label": "Expired", "value": expired, "status": "critical" if expired else "ok"},
                        {"label": "Not checked", "value": len(nc), "status": "warning" if nc else "ok"}]
                       + ([] if ro else [{"label": "CSRs made", "value": len([r for r in res.values() if r.get("status") == "made"])}]),
            "sections": sections}


class FilterModule(object):
    def filters(self):
        return {"vmware_cert_vmca": vmware_cert_vmca, "vmware_cert_plan": vmware_cert_plan,
                "vmware_cert_csr_result": vmware_cert_csr_result, "vmware_cert_report": vmware_cert_report}
